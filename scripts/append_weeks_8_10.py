def upsert(X, Y, x, y):
    x = np.asarray(x, dtype=float)
    for i in range(len(Y)):
        if np.allclose(X[i], x, atol=1e-5):
            Y[i] = float(y)
            return X, Y, "updated"
    X = np.vstack([X, x.reshape(1, -1)])
    Y = np.append(Y, float(y))
    return X, Y, "appended"


for week in (8, 9, 10):
    print(f"=== Week {week} ===")
    for fn in range(1, 9):
        base = DATA_ROOT / f"function_{fn}"
        X = np.load(base / "initial_inputs.npy")
        Y = np.load(base / "initial_outputs.npy")
        X, Y, how = upsert(X, Y, WEEKS[week]["X"][fn], WEEKS[week]["Y"][fn])
        np.save(base / "initial_inputs.npy", X)
        np.save(base / "initial_outputs.npy", Y)
        print(f"F{fn}: {how} | n={len(Y)} | best={float(Y.max()):.6g}")
